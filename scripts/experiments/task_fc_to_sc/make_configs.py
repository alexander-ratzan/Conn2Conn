"""Generate configs/<condition>.yml: the v2:E2.2 PCA-PLS learnable benchmark config + a data block selecting the FC
condition (spec v3 E0). Same search space for every condition; only data.fc_source_condition differs."""
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = next(p for p in HERE.parents if (p / "main.py").exists())


def main():
    cfg = yaml.safe_load((HERE / "config.yml").read_text())
    base = yaml.safe_load((REPO_ROOT / cfg["base_config"]).read_text())
    out = HERE / "configs"
    out.mkdir(exist_ok=True)
    for cond in cfg["conditions"]:
        c = {k: v for k, v in base.items() if k != "benchmark"}
        c["default"] = dict(c["default"])
        c["default"]["data"] = {"parcellation": cfg["parcellation"], "fc_conditions": list(cfg["task_conditions"]),
                                "expose_fc_sessions": True, "fc_source_condition": cond}
        c["task_fc_to_sc"] = {"condition": cond, "campaign": cfg["campaign"], "base_config": cfg["base_config"]}
        text = (f"# GENERATED by scripts/experiments/task_fc_to_sc/make_configs.py (spec v3 E0) from {cfg['base_config']}.\n"
                f"# FC source condition: {cond}. Do not edit; edit config.yml / make_configs.py.\n")
        (out / f"{cond}.yml").write_text(text + yaml.safe_dump(c, sort_keys=False, width=120))
        print("wrote", out / f"{cond}.yml")


if __name__ == "__main__":
    main()

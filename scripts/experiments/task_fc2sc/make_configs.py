"""Generate configs/<parcellation>/<condition>.yml: the v2:E2.2 PCA-PLS learnable benchmark config + a data block
selecting the parcellation and the FC condition (spec v3 E0). Same search space for every condition; only
data.fc_source_condition differs. Direction-free: the launcher's --source / --target set it."""
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = next(p for p in HERE.parents if (p / "main.py").exists())


def main():
    cfg = yaml.safe_load((HERE / "config.yml").read_text())
    base = yaml.safe_load((REPO_ROOT / cfg["base_config"]).read_text())
    for parc in dict.fromkeys(st["parcellation"] for st in cfg["steps"].values()):
        out = HERE / "configs" / parc
        out.mkdir(parents=True, exist_ok=True)
        for cond in cfg["conditions"]:
            c = {k: v for k, v in base.items() if k != "benchmark"}
            c["default"] = dict(c["default"])
            c["default"]["data"] = {"parcellation": parc, "fc_conditions": list(cfg["task_conditions"]),
                                    "expose_fc_sessions": True, "fc_source_condition": cond}
            c["task_fc2sc"] = {"condition": cond, "campaign": cfg["campaign"], "base_config": cfg["base_config"]}
            text = (f"# GENERATED by scripts/experiments/task_fc2sc/make_configs.py (spec v3 E0) from {cfg['base_config']}.\n"
                    f"# FC condition: {cond} ({parc}). Do not edit; edit config.yml / make_configs.py.\n")
            (out / f"{cond}.yml").write_text(text + yaml.safe_dump(c, sort_keys=False, width=120))
            print("wrote", out / f"{cond}.yml")


if __name__ == "__main__":
    main()

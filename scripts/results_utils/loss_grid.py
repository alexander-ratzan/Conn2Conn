"""Composite-loss protocol (spec v2 E1): shared code for every model instance.

An instance is a folder `scripts/experiments/composite_loss/<instance>/` with a hand-written `config.yml` and a
generated `state.yml` (Stage 1 tune ids, consensus config, reference scales). The protocol grid is
`scripts/experiments/composite_loss/grid.yml`. The CLI is `scripts/experiments/composite_loss/protocol.py`.

Stages and the helpers they use:
    Stage 1 summary   find_stage1_runs, collect_stage1_trials, stage1_summary, consensus_config
    E1.3 consensus    build_run_override (MSE-only), measure_term_scales, reference_scales, seed_best_configs
    E1.4 grid         combo_loss_trainer (fixed scales, loss_normalize none, inactive terms monitored)
    both              run_one (one model x seed run in its own process), TermGradCosine (optional callback)
    E1.5 report       collect_runs (concatenates per-run outputs into seed_records / epoch_history)

Per-run outputs (one file pair per run, so parallel processes never share a file):
    <instance>/runs/<stage>/<combo>__seed<k>.json          metrics, loss signature, scales (consensus stage)
    <instance>/runs/<stage>/<combo>__seed<k>__epochs.csv   per-epoch history (all four raw terms, val metrics)
"""
import glob
import json
import math
import os
import re
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

REPO_ROOT = next(p for p in Path(__file__).resolve().parents if (p / "main.py").exists())
EXPERIMENT_DIR = REPO_ROOT / "scripts" / "experiments" / "composite_loss"
RAY_CHECKPOINTS_DIR = REPO_ROOT / "results" / "ray_checkpoints"
LOG_DIR = REPO_ROOT / "results" / "logs"
TERMS = ("varmatch", "correye", "correye_dm", "neidist")
EXCLUSIVE_TERMS = (("correye", "correye_dm"),)   # never active together in one combination
ALL_TERMS = ("mse",) + TERMS
METRICS = ("demeaned_pearson", "avg_rank", "pearson", "mse", "top1_acc", "r2")


# --------------------------------------------------------------------------------------------- instance I/O
def instance_dir(instance):
    return EXPERIMENT_DIR / instance


def load_instance(instance):
    """Instance config merged with its protocol grid and generated state."""
    d = instance_dir(instance)
    cfg = yaml.safe_load((d / "config.yml").read_text())
    cfg["instance"] = instance
    cfg["grid"] = yaml.safe_load((REPO_ROOT / cfg["grid_file"]).read_text())
    if cfg["grid"]["version"] != cfg["grid_version"]:
        raise ValueError(f"{instance}: config grid_version {cfg['grid_version']} != grid file {cfg['grid']['version']}")
    for c in cfg["grid"]["combos"]:
        unknown = set(c) - {"id", "block"} - set(TERMS)
        if unknown:
            raise ValueError(f"{instance}: combination {c['id']} has unknown terms {sorted(unknown)}")
        for group in EXCLUSIVE_TERMS:
            if sum(float(c.get(x, 0.0)) > 0 for x in group) > 1:
                raise ValueError(f"{instance}: combination {c['id']} activates mutually exclusive terms {group}")
    cfg["state"] = load_state(instance)
    return cfg


def load_state(instance):
    path = instance_dir(instance) / "state.yml"
    if not path.exists():
        return {}
    return yaml.safe_load(path.read_text()) or {}


def update_state(instance, **fields):
    """Merge fields into <instance>/state.yml (generated; config.yml stays hand-written)."""
    state = load_state(instance)
    state.update(_plain(fields))
    path = instance_dir(instance) / "state.yml"
    header = "# Generated by scripts/experiments/composite_loss/protocol.py; do not edit by hand.\n"
    path.write_text(header + yaml.safe_dump(state, sort_keys=False))
    return state


def _plain(obj):
    """numpy scalars / arrays -> python types, for YAML / JSON."""
    if isinstance(obj, dict):
        return {(k.item() if isinstance(k, np.generic) else k): _plain(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_plain(v) for v in obj]
    if isinstance(obj, np.generic):
        return obj.item()
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    return obj


# --------------------------------------------------------------------------------------------- Stage 1
def _launcher_job_name(launcher):
    m = re.search(r"^#SBATCH --job-name=(\S+)", (REPO_ROOT / launcher).read_text(), re.M)
    if not m:
        raise ValueError(f"no --job-name in {launcher}")
    return m.group(1)


def find_stage1_runs(cfg, log_dir=LOG_DIR):
    """{seed: ray_tune_id} from the Stage 1 task logs (latest finished tune per seed)."""
    job = _launcher_job_name(cfg["stage1"]["launcher"])
    found = {}
    for path in sorted(glob.glob(os.path.join(str(log_dir), f"{job}_*_*.out")), key=os.path.getmtime):
        text = Path(path).read_text(errors="replace")
        seed, tune, done = re.search(r"Seed=(\d+)", text), re.search(r"Tune run: \S+_tune_(\d+)", text), "Tune finished" in text
        if seed and tune and done:
            found[int(seed.group(1))] = {"ray_tune_id": tune.group(1), "log": os.path.relpath(path, REPO_ROOT)}
    return dict(sorted(found.items()))


def collect_stage1_trials(model, runs, ckpt_root=RAY_CHECKPOINTS_DIR):
    """One row per Stage 1 trial (params, last val_demeaned_r, epochs) and one row per trial-epoch (monitor terms)."""
    trials, epochs = [], []
    for seed, info in runs.items():
        sweep = Path(ckpt_root) / f"{model}_tune_{info['ray_tune_id']}"
        for tdir in sorted(sweep.glob("_tune_trainable_*")):
            try:
                params = json.loads((tdir / "params.json").read_text())
                results = [json.loads(line) for line in (tdir / "result.json").read_text().splitlines() if line.strip()]
            except (OSError, ValueError):
                continue
            vals = [r["val_demeaned_r"] for r in results if r.get("val_demeaned_r") is not None]
            m = re.match(r"_tune_trainable_[0-9a-f]+_(\d+)", tdir.name)  # <hash>_<trial index>_<params>
            trial = m.group(1) if m else tdir.name
            trials.append({"seed": seed, "ray_tune_id": info["ray_tune_id"], "trial": trial, "trial_dir": tdir.name,
                           "n_epochs": len(results), "val_demeaned_r": vals[-1] if vals else np.nan,
                           "time_s": results[-1].get("time_total_s") if results else np.nan,
                           **{f"p.{k}": v for k, v in params.items()}})
            for r in results:
                epochs.append({"seed": seed, "trial": trial, "epoch": r.get("training_iteration"),
                               "val_demeaned_r": r.get("val_demeaned_r"),
                               **{k: r.get(k) for k in r if re.match(r"(train|val)_loss_raw_", k)}})
    return pd.DataFrame(trials), pd.DataFrame(epochs)


def stage1_summary(trials, min_best_val=None):
    """Per-seed best trial, budget convergence, and the Stage 1 stop check."""
    rows = []
    for seed, g in trials.groupby("seed"):
        g = g.sort_values("trial", key=lambda s: s.astype(int))
        best_so_far = g["val_demeaned_r"].cummax().to_numpy()
        n = len(best_so_far)
        best = g.loc[g["val_demeaned_r"].idxmax()]
        rows.append({"seed": seed, "n_trials": n, "best_val": best["val_demeaned_r"], "best_trial": best["trial"],
                     "best_at_trial": int(np.argmax(best_so_far >= best["val_demeaned_r"])) + 1,
                     "best_after_half": best_so_far[n // 2 - 1] if n >= 2 else np.nan})
    summary = pd.DataFrame(rows)
    stop = []
    if min_best_val is not None:
        weak = summary[summary["best_val"] < min_best_val]
        if len(weak):
            stop.append(f"Stage 1 best val below {min_best_val} for seeds {weak['seed'].tolist()}")
    return summary, stop


def consensus_config(trials, search_space):
    """Consensus of the per-seed best trials: categorical keys by majority (ties -> the best-scoring seed's value),
    loguniform keys by geometric median, uniform keys by median."""
    best = trials.loc[trials.groupby("seed")["val_demeaned_r"].idxmax()].sort_values("val_demeaned_r", ascending=False)
    out, detail = {}, {}
    for key, spec in search_space.items():
        col = f"p.{key}"
        vals = best[col].tolist()
        kind = spec.get("type")
        if kind in ("choice", "grid"):
            counts = pd.Series([json.dumps(v) for v in vals]).value_counts()
            top = counts[counts == counts.max()].index
            winner = next(json.dumps(v) for v in vals if json.dumps(v) in top)  # best-scoring seed breaks ties
            out[key] = json.loads(winner)
        elif kind == "loguniform":
            out[key] = float(math.exp(np.median(np.log(np.asarray(vals, dtype=float)))))
        elif kind == "uniform":
            out[key] = float(np.median(np.asarray(vals, dtype=float)))
        else:
            raise ValueError(f"unsupported search type {kind!r} for {key}")
        detail[key] = {"per_seed": _plain(vals), "consensus": out[key]}
    return _plain(out), detail


def consensus_accepted(consensus_val_by_seed, best_val_by_seed):
    """Accept if the consensus config's mean val is within 1 SE of the mean of the per-seed bests."""
    best = np.asarray(list(best_val_by_seed.values()), dtype=float)
    cons = np.asarray([consensus_val_by_seed[s] for s in best_val_by_seed], dtype=float)
    se = best.std(ddof=1) / math.sqrt(len(best)) if len(best) > 1 else 0.0
    gap = best.mean() - cons.mean()
    return bool(gap <= se), {"best_mean": best.mean(), "consensus_mean": cons.mean(), "se": se, "gap": gap}


def seed_best_configs(trials, search_space):
    """Each seed's own best Stage 1 trial as a config, with max_epochs capped at the epochs the trial actually
    trained (ASHA may stop it early; same rule as main.py's best-trial refit)."""
    out = {}
    for seed, g in trials.groupby("seed"):
        best = g.loc[g["val_demeaned_r"].idxmax()]
        conf = {k: _plain(best[f"p.{k}"]) for k in search_space}
        if "max_epochs" in conf:
            conf["max_epochs"] = int(min(int(conf["max_epochs"]), int(best["n_epochs"])))
        out[int(seed)] = {"config": conf, "stage1_val": float(best["val_demeaned_r"]), "trial": str(best["trial"])}
    return out


# --------------------------------------------------------------------------------------------- loss configs
def split_consensus(consensus, stage1_config_path):
    """Consensus keys -> {"model": ..., "trainer": ...} overrides (trainer keys per models.registry)."""
    from models.registry import is_trainer_key
    model = {k: v for k, v in consensus.items() if not is_trainer_key(k)}
    trainer = {k: v for k, v in consensus.items() if is_trainer_key(k)}
    return {"model": model, "trainer": trainer}


def combo_loss_trainer(combo, scales, batch_size):
    """Trainer overrides for one grid combination: MSE anchor + scaled active terms, the rest monitored."""
    for group in EXCLUSIVE_TERMS:
        on = [x for x in group if float(combo.get(x, 0.0)) > 0]
        if len(on) > 1:
            raise ValueError(f"combination {combo.get('id')}: {on} are mutually exclusive")
    terms = [{"name": "mse", "weight": 1.0}]
    monitors = []
    for t in TERMS:
        w = float(combo.get(t, 0.0))
        if w > 0:
            terms.append({"name": t, "weight": w, "kwargs": {"scale": float(scales[t])}})
        else:
            monitors.append(t)
    return {"loss_type": "composite", "loss_terms": terms, "loss_normalize": "none",
            "loss_monitor_terms": monitors or None, "batch_size": int(batch_size), "log_every": 1}


def mse_only_trainer(batch_size):
    return combo_loss_trainer({t: 0.0 for t in TERMS}, {t: 1.0 for t in TERMS}, batch_size)


def expected_signature(combo):
    parts = ["mse"] + [t if float(combo.get(t, 0)) == 1.0 else f"{float(combo[t]):g}*{t}" for t in TERMS if float(combo.get(t, 0)) > 0]
    return "+".join(parts)


# --------------------------------------------------------------------------------------------- scales
def term_functions(target_mean):
    """{term: f(y_pred, y_true)} for every protocol term; correye_dm needs the training-set target mean."""
    import torch
    import torch.nn.functional as F
    from models.train.loss import compute_var_match_loss, compute_correye_loss, compute_correye_dm_loss, compute_neidist_loss
    tm = torch.as_tensor(np.asarray(target_mean), dtype=torch.float32)
    return {"mse": F.mse_loss, "varmatch": compute_var_match_loss, "correye": compute_correye_loss,
            "correye_dm": lambda p, y: compute_correye_dm_loss(p, y, tm.to(p.device)), "neidist": compute_neidist_loss}


def measure_term_scales(model, dataset, batch_size, device=None):
    """Mean |raw| and mean signed raw of every term over full training batches (eval mode, fixed order)."""
    import torch
    from torch.utils.data import DataLoader
    from models.utils import predict_from_loader
    from models.train.loss import get_target_train_mean
    fns = term_functions(get_target_train_mean(dataset.base))
    loader = DataLoader(dataset, batch_size=batch_size, shuffle=False)
    model.eval()
    preds, targets = predict_from_loader(model, loader)
    preds, targets = torch.as_tensor(np.asarray(preds), dtype=torch.float32), torch.as_tensor(np.asarray(targets), dtype=torch.float32)
    n_full = preds.shape[0] // batch_size
    raw = {t: [] for t in ALL_TERMS}
    with torch.no_grad():
        for b in range(n_full):  # a partial last batch would change the batch-dependent terms
            sl = slice(b * batch_size, (b + 1) * batch_size)
            for t, fn in fns.items():
                raw[t].append(float(fn(preds[sl], targets[sl])))
    return {t: {"abs_mean": float(np.mean(np.abs(v))), "mean": float(np.mean(v)), "n_batches": len(v)} for t, v in raw.items()}


def reference_scales(scales_by_seed):
    """c_t = mean_seeds(s_t) / mean_seeds(s_mse), with the across-seed spread of the per-seed ratios."""
    seeds = sorted(scales_by_seed)
    s = {t: np.array([scales_by_seed[k][t]["abs_mean"] for k in seeds]) for t in ALL_TERMS}
    out = {"c": {}, "spread_cv": {}, "s_abs_mean": {t: float(s[t].mean()) for t in ALL_TERMS},
           "neidist_signed_mean": float(np.mean([scales_by_seed[k]["neidist"]["mean"] for k in seeds])), "seeds": seeds}
    for t in TERMS:
        ratios = s[t] / s["mse"]
        out["c"][t] = float(s[t].mean() / s["mse"].mean())
        out["spread_cv"][t] = float(ratios.std(ddof=1) / ratios.mean()) if len(seeds) > 1 else 0.0
    return out


# --------------------------------------------------------------------------------------------- gradient cosines
class TermGradCosine:
    """Lightning callback factory: every `every` epochs, gradients of each term w.r.t. one parameter on a fixed
    training batch; logs pairwise cosines and gradient norms (rows in `.rows`). Built lazily so importing this module
    does not import Lightning."""

    def __new__(cls, param_name, every=5, terms=ALL_TERMS, target_mean=None):
        import lightning.pytorch as pl
        import torch
        import torch.nn.functional as F
        if target_mean is not None:
            fns = term_functions(target_mean)
        else:  # no target mean: correye_dm cannot be computed
            terms = [t for t in terms if t != "correye_dm"]
            from models.train.loss import compute_var_match_loss, compute_correye_loss, compute_neidist_loss
            fns = {"mse": F.mse_loss, "varmatch": compute_var_match_loss, "correye": compute_correye_loss, "neidist": compute_neidist_loss}

        class _Callback(pl.Callback):
            def __init__(self):
                self.param_name, self.every, self.terms, self.rows, self._batch = param_name, every, list(terms), [], None

            def on_train_batch_start(self, trainer, pl_module, batch, batch_idx):
                if self._batch is None:  # first training batch, kept fixed for every measurement
                    self._batch = {k: (v.detach().clone() if torch.is_tensor(v) else v) for k, v in batch.items()}

            def on_train_epoch_end(self, trainer, pl_module):
                epoch = trainer.current_epoch
                if self._batch is None or (epoch % self.every and epoch != trainer.max_epochs - 1):
                    return
                params = dict(pl_module.model.named_parameters())
                if self.param_name not in params or not params[self.param_name].requires_grad:
                    # fall back to the first trainable 2-D weight (recorded in the rows)
                    self.param_name = next(n for n, q in params.items() if q.requires_grad and q.dim() == 2)
                param = params[self.param_name]
                batch = {k: (v.to(pl_module.device) if torch.is_tensor(v) else v) for k, v in self._batch.items()}
                was_training = pl_module.training
                pl_module.eval()
                with torch.enable_grad():
                    y_pred, _, _ = pl_module._unpack_out(pl_module._forward_model(batch))
                    y = batch["y"]
                    grads = {}
                    for t in self.terms:
                        g, = torch.autograd.grad(fns[t](y_pred, y), param, retain_graph=True)
                        grads[t] = g.flatten()
                if was_training:
                    pl_module.train()
                row = {"epoch": epoch, "grad_param": self.param_name, **{f"gnorm_{t}": float(grads[t].norm()) for t in self.terms}}
                for i, a in enumerate(self.terms):
                    for b in self.terms[i + 1:]:
                        row[f"cos_{a}_{b}"] = float(F.cosine_similarity(grads[a], grads[b], dim=0))
                self.rows.append(row)

        return _Callback()


# --------------------------------------------------------------------------------------------- one run
def run_one(instance, stage, combo_id, seed, trainer_overrides, grad_cosine=None, mode="prod", out_root=None, hparams=None):
    """Train + evaluate one (combination, seed) with the instance's consensus config (or `hparams` in its place).
    Writes the run's JSON and epoch CSV and returns the JSON record. Meant to run in its own process (see protocol.py)."""
    import inspect
    from main import Sim
    cfg = load_instance(instance)
    state = cfg["state"]
    if "consensus" not in state:
        raise RuntimeError(f"{instance}: no consensus in state.yml (run the stage1 step first)")
    batch = int(cfg["grid"]["batch_size"])
    override = split_consensus(hparams if hparams is not None else state["consensus"], cfg["stage1"]["config"])
    override["trainer"] = {**override["trainer"], **trainer_overrides}
    sim = Sim(model_name=cfg["model"], config_path=str(REPO_ROOT / cfg["stage1"]["config"]), source=cfg["source"],
              target=cfg["target"], shuffle_seed=int(seed), data_load_mode="precomputed", batch_size=batch)
    tags = [cfg["model"], f"loss_grid:{cfg['grid_version']}", f"composite_loss:{stage}", f"combo:{combo_id}"]
    kwargs = dict(mode=mode, save_checkpoint=False, config_override=override, wandb_tags=tags,
                  wandb_name=f"{cfg['model']}_{stage}_{combo_id}_s{seed}", run_eval=True)
    cb = None
    if grad_cosine:
        if "extra_callbacks" in inspect.signature(Sim._run_learned_single).parameters:
            from models.train.loss import get_target_train_mean
            cb = TermGradCosine(grad_cosine["param"], every=int(grad_cosine.get("every", 5)),
                                target_mean=get_target_train_mean(sim.base))
            kwargs["extra_callbacks"] = [cb]
        else:
            print("grad cosine skipped: Sim._run_learned_single has no extra_callbacks parameter", flush=True)
    run_out = sim._run_learned_single(**kwargs)
    try:
        import wandb
        if wandb.run is not None:
            wandb.finish()
    except ImportError:
        pass
    tr = run_out["train_result"]
    hist = tr.history_df.copy()
    rec = {"model": cfg["model"], "instance": instance, "grid_version": cfg["grid_version"], "stage": stage,
           "combo_id": combo_id, "seed": int(seed), "batch_size": batch, "hparams": hparams,
           "loss_signature": dict(tr.pl_module.hparams).get("loss_signature"),
           "val_demeaned_r_last": float(hist["val_demeaned_r"].dropna().iloc[-1]) if "val_demeaned_r" in hist else None,
           "epochs": int(len(hist))}
    for split in ("train", "val", "test"):
        for m in METRICS:
            v = (run_out["metrics"].get(split) or {}).get(m)
            rec[f"{split}_{m}"] = float(v) if v is not None else None
    if stage == "consensus":
        rec["term_scales"] = measure_term_scales(run_out["model"], sim.train_ds, batch)
    out = Path(out_root) if out_root else instance_dir(instance) / "runs" / stage
    out.mkdir(parents=True, exist_ok=True)
    stem = f"{combo_id}__seed{int(seed)}"
    if cb is not None and cb.rows:
        cos = pd.DataFrame(cb.rows)
        hist = hist.merge(cos, on="epoch", how="left") if "epoch" in hist else hist
    hist.insert(0, "seed", int(seed))
    hist.insert(0, "combo_id", combo_id)
    hist.to_csv(out / f"{stem}__epochs.csv", index=False)
    (out / f"{stem}.json").write_text(json.dumps(_plain(rec), indent=2))
    return rec


# --------------------------------------------------------------------------------------------- report inputs
def collect_runs(instance, stage):
    """Concatenate a stage's per-run outputs into (seed_records, epoch_history) DataFrames."""
    d = instance_dir(instance) / "runs" / stage
    recs = [json.loads(p.read_text()) for p in sorted(d.glob("*.json"))]
    seed_records = pd.DataFrame([{k: v for k, v in r.items() if k != "term_scales"} for r in recs])
    epochs = [pd.read_csv(p) for p in sorted(d.glob("*__epochs.csv"))]
    epoch_history = pd.concat(epochs, ignore_index=True) if epochs else pd.DataFrame()
    return seed_records, epoch_history
